// Copies the compiled ABIs from ../contracts/out into src/abi.ts (and ../app/lib/abi.ts when the app
// exists), so the worker, the app and the contracts can never drift. Run after any `forge build`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../contracts/out");
// Events keep type, name and inputs only: none of these contracts declares a topic-less event, and the
// flag forge emits for that is false everywhere, which is also its default.
const slim = (abi) => abi.map((x) => (x.type === "event" ? { type: x.type, name: x.name, inputs: x.inputs } : x));
const read = (file, name) => slim(JSON.parse(fs.readFileSync(path.join(out, file, `${name}.json`), "utf8")).abi);

